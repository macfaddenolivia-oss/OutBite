#!/usr/bin/env node
// One-time helper: turns the U.S. state outlines from us-atlas (U.S. Census Bureau
// cartographic boundary files, 2017, public domain; packaged by us-atlas, ISC license)
// into SVG path strings keyed by postal code, saved as src/data/us-map.json, plus
// separate outlines of the five territories for the map insets.
// The outlines are already projected (Albers USA, Alaska and Hawaii inset) to a
// 975×610 frame. Run again only if the source package changes:
//   node scripts/build-map.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { splitNotes } from './data-lib.mjs';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const topo = JSON.parse(readFileSync(require.resolve('us-atlas/states-albers-10m.json'), 'utf8'));

// State FIPS code → postal code.
const FIPS = {
  '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE',
  '11': 'DC', '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA',
  '20': 'KS', '21': 'KY', '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN',
  '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM',
  '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI',
  '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA',
  '54': 'WV', '55': 'WI', '56': 'WY',
};

const r = (n) => Math.round(n * 10) / 10;
const ring = (pts) => 'M' + pts.map(([x, y]) => `${r(x)} ${r(y)}`).join('L') + 'Z';

const states = {};
const centers = {};
for (const f of feature(topo, topo.objects.states).features) {
  const code = FIPS[f.id];
  if (!code) throw new Error(`Unknown FIPS ${f.id}`);
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  states[code] = polys.map((p) => p.map(ring).join('')).join('');
  // Label point: centre of the largest polygon's bounding box.
  let best = null;
  for (const p of polys) {
    const xs = p[0].map((q) => q[0]);
    const ys = p[0].map((q) => q[1]);
    const box = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
    const area = (box[2] - box[0]) * (box[3] - box[1]);
    if (!best || area > best.area) best = { box, area };
  }
  centers[code] = [r((best.box[0] + best.box[2]) / 2), r((best.box[1] + best.box[3]) / 2)];
}

// Territories: the same Census Bureau files, unprojected (us-atlas states-10m.json, which
// includes them), each drawn on its own as a dashboard inset. Simple projection
// (longitude scaled by the cosine of the middle latitude), fit to 100 units on the
// longer side. Northern Mariana Islands: only the southern islands where most people
// live (Saipan, Tinian, Aguijan, Rota; south of 15.4°N); the northern islands spread
// over 500 km and would shrink the inset to dots.
const geo = JSON.parse(readFileSync(require.resolve('us-atlas/states-10m.json'), 'utf8'));
const TERRITORY_FIPS = { '72': 'PR', '78': 'VI', '66': 'GU', '69': 'MP', '60': 'AS' };
const territories = {};
for (const f of feature(geo, geo.objects.states).features) {
  const code = TERRITORY_FIPS[f.id];
  if (!code) continue;
  let polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  if (code === 'MP') polys = polys.filter((p) => Math.max(...p[0].map((q) => q[1])) < 15.4);
  const pts = polys.flatMap((p) => p[0]);
  const [x0, x1] = [Math.min(...pts.map((q) => q[0])), Math.max(...pts.map((q) => q[0]))];
  const [y0, y1] = [Math.min(...pts.map((q) => q[1])), Math.max(...pts.map((q) => q[1]))];
  const k = Math.cos((((y0 + y1) / 2) * Math.PI) / 180);
  const scale = 100 / Math.max((x1 - x0) * k, y1 - y0);
  const project = ([lon, lat]) => [(lon - x0) * k * scale, (y1 - lat) * scale];
  territories[code] = {
    d: polys.map((p) => p.map((rg) => ring(rg.map(project))).join('')).join(''),
    width: r((x1 - x0) * k * scale),
    height: r((y1 - y0) * scale),
  };
}
for (const code of Object.values(TERRITORY_FIPS)) if (!territories[code]) throw new Error(`Missing territory ${code}`);

const out = {
  _source:
    'U.S. Census Bureau cartographic boundary files (2017), public domain, via the us-atlas package (states-albers-10m.json for the states and DC; states-10m.json for the territory insets; ISC license). Generated by scripts/build-map.mjs.',
  width: 975,
  height: 610,
  states,
  centers,
  territories,
};
const file = join(root, 'src/data/us-map.json');
writeFileSync(file, JSON.stringify(splitNotes(root, file, out)) + '\n');
